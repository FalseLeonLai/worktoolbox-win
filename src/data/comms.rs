//! 通信参考数据（PLC 数据类型 / 常用协议速查）（内容生产线填充；须保持本文件公开 API 不变）

pub struct DataType {
    pub name: &'static str,  // 如 "INT"
    pub size: &'static str,  // 如 "16 bit"
    pub range: &'static str, // 如 "-32768 ~ 32767"
    pub note: &'static str,  // 工程备注
}

pub struct Protocol {
    pub name: &'static str,
    pub summary: &'static str,
    pub points: Vec<&'static str>,
}

